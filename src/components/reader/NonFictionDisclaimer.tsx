import { Info, X } from 'lucide-react';
import { AnimatePresence, motion } from 'motion/react';
import type React from 'react';
import { useEffect, useState } from 'react';
import { createPortal } from 'react-dom';

interface NonFictionDisclaimerProps {
  className?: string;
}

export const NonFictionDisclaimer: React.FC<NonFictionDisclaimerProps> = ({
  className = '',
}) => {
  const [isModalOpen, setIsModalOpen] = useState(false);

  useEffect(() => {
    if (!isModalOpen) return;
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === 'Escape') {
        setIsModalOpen(false);
      }
    };
    window.addEventListener('keydown', handleKeyDown);
    return () => window.removeEventListener('keydown', handleKeyDown);
  }, [isModalOpen]);

  return (
    <div
      className={`flex items-center gap-1.5 text-slate-400 dark:text-slate-500 text-[11px] sm:text-xs w-full ${className}`}
    >
      <button
        type="button"
        onClick={() => setIsModalOpen(true)}
        className="group inline-flex items-center gap-1.5 text-left hover:text-slate-600 dark:hover:text-slate-300 transition-colors cursor-pointer select-none"
        title="Click to view full AI disclaimer"
      >
        <Info className="w-3.5 h-3.5 text-slate-400 dark:text-slate-500 group-hover:text-slate-600 dark:group-hover:text-slate-300 shrink-0 transition-colors" />
        <span>
          <span className="font-medium text-slate-500 dark:text-slate-400 group-hover:text-slate-700 dark:group-hover:text-slate-200">
            AI Disclaimer:{' '}
          </span>
          Generated by AI for language learning and reading practice.{' '}
          <span className="underline font-medium underline-offset-2">
            Read full disclaimer
          </span>
        </span>
      </button>

      <AnimatePresence>
        {isModalOpen &&
          typeof document !== 'undefined' &&
          createPortal(
            <div
              role="dialog"
              aria-modal="true"
              aria-labelledby="ai-disclaimer-modal-title"
              className="fixed inset-0 z-[100] flex items-center justify-center p-4 sm:p-6"
            >
              {/* Backdrop */}
              <motion.div
                initial={{ opacity: 0 }}
                animate={{ opacity: 1 }}
                exit={{ opacity: 0 }}
                onClick={() => setIsModalOpen(false)}
                className="fixed inset-0 bg-[#0f172a]/60 backdrop-blur-sm"
              />

              {/* Modal card */}
              <motion.div
                initial={{ scale: 0.95, opacity: 0, y: 12 }}
                animate={{ scale: 1, opacity: 1, y: 0 }}
                exit={{ scale: 0.95, opacity: 0, y: 12 }}
                transition={{ type: 'spring', duration: 0.3 }}
                className="relative bg-tj-bg-card rounded-2xl border border-tj-border-main shadow-2xl max-w-md w-full p-6 space-y-4 overflow-hidden z-10 flex flex-col"
              >
                {/* Close Button */}
                <button
                  type="button"
                  onClick={() => setIsModalOpen(false)}
                  className="absolute top-4 right-4 p-1.5 hover:bg-tj-bg-recessed text-tj-text-muted hover:text-tj-text-main rounded-full cursor-pointer transition-colors"
                  aria-label="Close disclaimer modal"
                >
                  <X className="w-4 h-4" />
                </button>

                <div className="flex items-start gap-3.5 pr-6">
                  <div className="p-2.5 rounded-xl bg-tj-primary-light dark:bg-tj-primary-light/10 text-tj-primary dark:text-tj-primary-hover shrink-0">
                    <Info className="w-5 h-5" />
                  </div>
                  <div>
                    <h3
                      id="ai-disclaimer-modal-title"
                      className="text-base font-bold text-slate-800 dark:text-slate-100 font-sans"
                    >
                      AI Disclaimer
                    </h3>
                    <p className="text-xs text-slate-400 dark:text-slate-500 font-medium">
                      Easy eBooks &amp; Language Learning
                    </p>
                  </div>
                </div>

                <div className="text-xs sm:text-sm text-slate-600 dark:text-slate-300 leading-relaxed space-y-2.5 font-sans pt-1">
                  <p>
                    Generated by AI for language learning and reading practice.
                    Facts and details have not been independently verified.
                  </p>
                  <p>
                    Not intended as medical, legal, financial, or safety advice.
                    Fictional characters, names, and situations do not depict or
                    represent real living persons.
                  </p>
                </div>

                <div className="pt-2 flex items-center justify-end">
                  <button
                    type="button"
                    onClick={() => setIsModalOpen(false)}
                    className="w-full sm:w-auto px-5 py-2 bg-slate-900 hover:bg-slate-800 text-white dark:bg-slate-100 dark:hover:bg-white dark:text-slate-900 text-xs font-bold rounded-xl transition-all shadow-sm cursor-pointer select-none"
                  >
                    Got it
                  </button>
                </div>
              </motion.div>
            </div>,
            document.body,
          )}
      </AnimatePresence>
    </div>
  );
};

export default NonFictionDisclaimer;
